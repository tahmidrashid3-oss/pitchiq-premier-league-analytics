
from pathlib import Path
import sys

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app import create_team_history, build_prediction_features

RAW_FILE = (
    ROOT / "data" / "processed"
    / "premier_league_with_xg.csv"
)

FEATURE_FILE = (
    ROOT / "data" / "processed"
    / "match_features_advanced.csv"
)

WINDOWS = [3, 5, 10]

METRICS = [
    "Points",
    "GoalsFor",
    "GoalsAgainst",
    "xGFor",
    "xGAgainst",
]

FEATURES = [
    f"Diff_{prefix}_{metric}_Last{window}"
    for prefix in ["Overall", "Venue"]
    for window in WINDOWS
    for metric in METRICS
]


def main():
    print("=" * 65)
    print("PITCHIQ — FEATURE CONSISTENCY TEST")
    print("=" * 65)

    raw = pd.read_csv(
        RAW_FILE,
        dtype={"Season": str},
        parse_dates=["Date"],
    )

    advanced = pd.read_csv(
        FEATURE_FILE,
        dtype={"Season": str},
        parse_dates=["Date"],
    )

    history = create_team_history(raw)

    # Compare historical fixtures against the features
    # originally generated by the training pipeline.
    #
    # Using a sample keeps the test reasonably fast.
    sample = advanced.sample(
        n=min(200, len(advanced)),
        random_state=42,
    )

    differences = []
    mismatched_matches = 0

    for _, match in sample.iterrows():

        X, _ = build_prediction_features(
            history=history,
            home_team=match["HomeTeam"],
            away_team=match["AwayTeam"],
            as_of_date=match["Date"],
            expected_features=FEATURES,
        )

        expected = match[FEATURES].to_numpy(
            dtype=float
        )

        actual = X.iloc[0][FEATURES].to_numpy(
            dtype=float
        )

        error = np.abs(expected - actual)

        differences.extend(error)

        if not np.allclose(
            expected,
            actual,
            atol=1e-8,
            rtol=1e-8,
        ):
            mismatched_matches += 1

    max_difference = max(differences)
    mean_difference = float(np.mean(differences))

    print(f"Matches tested: {len(sample)}")
    print(f"Features per match: {len(FEATURES)}")
    print(f"Mismatched matches: {mismatched_matches}")
    print(f"Maximum absolute difference: {max_difference:.10f}")
    print(f"Mean absolute difference: {mean_difference:.10f}")

    if mismatched_matches == 0:
        print("\nPASS — Dashboard and training features match.")
    else:
        print(
            "\nFAIL — Some dashboard features differ "
            "from the training pipeline."
        )


if __name__ == "__main__":
    main()
